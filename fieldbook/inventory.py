"""Generate an auditable map of every declared upstream package-root symbol."""

import argparse
from pathlib import Path

import cpg2unstructured
import fault_projections


ROOT = Path(__file__).resolve().parents[1]
PAGES = {
    "grid-input.md": {"read_grdecl", "read_egrid", "Grdecl", "CornerPointGrid"},
    "topology-quality.md": {
        "from_grdecl", "build_topology", "check_validity", "cell_quality",
        "CornerCube", "UnstructuredGrid", "QualityReport", "ValidityReport",
    },
    "morph-pillars.md": {
        "morph_pillars", "PillarTargets", "MorphResult",
        "ValidityExhausted", "ValidityExhaustedWarning",
    },
    "targets-corridors.md": {"targets_from_polyline", "targets_from_polylines"},
    "adapt-grid.md": {
        "adapt_grid", "adapt_deck", "AdaptResult", "surface_top_trace", "live_faces",
    },
    "surface-projection.md": {
        "project_fault_surface", "project_quad_mesh_surface",
        "FaultSurface", "QuadMesh",
    },
    "fault-slide.md": {
        "slide_grid", "slide_deck", "Throw", "SlideResult", "SlideError", "Connection",
        "zcorn_cube", "with_zcorn", "apply_zcorn_displacement", "unwelded_faces",
        "zcorn_validity", "ZcornValidity", "write_slide_png",
    },
}


def render() -> str:
    lines = [
        "# Declared upstream API inventory",
        "",
        "Generated by `python -m fieldbook.inventory --write` against the",
        "pinned upstream revisions. `__all__` is not proof of importability:",
        "the table checks each name at the package root. A function page",
        "covers its named calls; a directory-only entry is **not yet a",
        "MATLAB-style reference**. Regenerate and review this inventory",
        "when changing `upstream-lock.toml`.",
        "",
        "| Package | Declared name | Root import | Detailed page |",
        "|---|---|---|---|",
    ]
    for module in (cpg2unstructured, fault_projections):
        for name in sorted(set(module.__all__)):
            page = next((page for page, names in PAGES.items() if name in names), None)
            href = f"[{page.removesuffix('.md')}](../functions/{page})" if page else "Directory only"
            availability = "yes" if hasattr(module, name) else "**NO (broken export)**"
            lines.append(f"| `{module.__name__}` | `{name}` | {availability} | {href} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="refresh the tracked inventory")
    args = parser.parse_args(argv)
    path = ROOT / "docs" / "reference" / "api-inventory.md"
    content = render()
    if args.write:
        path.write_text(content, encoding="utf-8")
        print(path)
    elif path.read_text(encoding="utf-8") != content:
        raise SystemExit("API inventory drift: regenerate and review it")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
